    private void jbGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbGuardarActionPerformed
         try {
        String dniStr = txtDNI.getText().trim();
        String nombre = txtNombre.getText().trim();
        String apellido = txtApellido.getText().trim();
        String correo = txtCorreo.getText().trim();
        String telefono = txtTelefono.getText().trim();
        

        if (dniStr.isEmpty() || nombre.isEmpty() || apellido.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, completa DNI, Nombre y Apellido.", "Campos Incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
    
        int dni;
        try {
            dni = Integer.parseInt(dniStr);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El DNI debe ser un número entero válido.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
            txtDNI.grabFocus();
            return;
        }
        boolean estado = BoxEstado.isSelected();


        Pasajero nuevoPasajero = new Pasajero(dniStr, nombre, apellido, correo, telefono, estado);

        PasajeroData pasajeroData = new PasajeroData();
        pasajeroData.guardarPasajero(nuevoPasajero); // 
        JOptionPane.showMessageDialog(this, "¡Pasajero guardado con éxito!");
        limpiarCampos();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al intentar guardar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
}                                         
private void limpiarCampos() {
    txtDNI.setText("");
    txtNombre.setText("");
    txtApellido.setText("");
    txtCorreo.setText("");
    txtTelefono.setText("");
    BoxEstado.setSelected(true);
    }//GEN-LAST:event_jbGuardarActionPerformed


